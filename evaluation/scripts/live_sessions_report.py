"""Latency in the team's real sessions on the hosted build (24 Oct 2026).

    python3 evaluation/scripts/live_sessions_report.py   # -> results/live_sessions_2026-10-24.md

Reads `evaluation/data/live_sessions_2026-10-24/sessions.json`: the latency block each stored
session summary carries (the browser stamps capture time on every frame; the service measures
capture -> event, its own processing, and event -> cue). One teammate (T1), a home laptop webcam,
real pegs and a real cup. No frames exist. This is speed, not accuracy: nobody labelled the reps.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "evaluation" / "data" / "live_sessions_2026-10-24" / "sessions.json"
OUT = ROOT / "evaluation" / "results" / "live_sessions_2026-10-24.md"
NAMES = {"cup": "Waiter – cup", "nhpt": "Nine-Hole Peg Test"}


def half_up(v: float) -> str:
    return f"{int(v + 0.5):,}"


def fmt(v: float | None) -> str:
    return "–" if v is None else half_up(v) if v >= 10 else f"{v:.1f}"


def main() -> int:
    d = json.loads(DATA.read_text())
    rows = sorted(d["sessions"], key=lambda r: (r["mode"], r["session"]))
    lines = [
        "# Latency in real sessions (hosted build, 24 Oct 2026)", "",
        f"Generated by `evaluation/scripts/live_sessions_report.py` from `{DATA.relative_to(ROOT)}`. "
        + d["source"] + " Capture → event includes the browser, the network and the server. "
        "Server processing is the OpenCV step alone. These sessions ran before the 24–25 Oct fixes "
        "(report §8.1.1). Speed only, not accuracy.", "",
        "| session | exercise | frames | capture → event p50 / p95 (ms) | server processing p50 / p95 (ms) | event → cue p50 / p95 (ms) |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for r in rows:
        lat = r["latency_ms"]
        lines.append(f"| `{r['session']}` | {NAMES[r['mode']]} | {lat['frames']:,} | "
                     f"{fmt(lat['capture_to_event_p50'])} / {fmt(lat['capture_to_event_p95'])} | "
                     f"{fmt(lat['proc_p50'])} / {fmt(lat['proc_p95'])} | "
                     f"{fmt(lat['event_to_cue_p50'])} / {fmt(lat['event_to_cue_p95'])} |")
    cup = [r["latency_ms"] for r in rows if r["mode"] == "cup"]
    rng = lambda k: f"{half_up(min(c[k] for c in cup))}–{half_up(max(c[k] for c in cup))}"  # noqa: E731
    lines += ["", f"**Waiter – cup, {len(cup)} sessions:** capture → event median {rng('capture_to_event_p50')} ms, "
              f"p95 {rng('capture_to_event_p95')} ms; server processing p95 {rng('proc_p95')} ms. "
              "The slow tail is the network or queueing, not OpenCV.", ""]
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
