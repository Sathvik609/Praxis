"""Local accounts and access control for the edge build (17 Sep 2026).

Three team accounts; passwords stored as salted PBKDF2-SHA256 hashes (override with the
PRAXIS_USERS env var: "user:Display:salt_hex:hash_hex,..."). Tokens are HMAC-signed and expire
(PRAXIS_AUTH_SECRET; a random per-process secret when unset, which signs everyone out on
restart). Sign-in is rate-limited per client address. Every /api route (except login), /events
and the session WebSocket require a valid token; /health and the static app stay public.
Cognito replaces this in cloud mode. No OpenCV here."""
from __future__ import annotations

import base64
import hashlib
import hmac
import os
import secrets
import time
from collections import defaultdict, deque
from typing import Any

PBKDF2_ROUNDS = 120_000
TOKEN_TTL_S = 12 * 3600
MAX_FAILURES = 8  # per client address
FAILURE_WINDOW_S = 10 * 60

# username -> (display name, salt hex, pbkdf2 hex); generated by tools/make_user.py
_DEFAULT_USERS: dict[str, tuple[str, str, str]] = {
    "rinky": ("Rinky", "***REMOVED***", "***REMOVED***"),
    "shruthi": ("Shruthi", "***REMOVED***", "***REMOVED***"),
    "sathvik": ("Sathvik", "***REMOVED***", "***REMOVED***"),
}


def _load_users() -> dict[str, tuple[str, str, str]]:
    raw = os.environ.get("PRAXIS_USERS", "").strip()
    if not raw:
        return dict(_DEFAULT_USERS)
    out: dict[str, tuple[str, str, str]] = {}
    for item in raw.split(","):
        user, name, salt, digest = item.strip().split(":")
        out[user.lower()] = (name, salt, digest)
    return out


_USERS = _load_users()
_SECRET = os.environ.get("PRAXIS_AUTH_SECRET", "").encode("utf-8") or secrets.token_bytes(32)
_failures: dict[str, deque[float]] = defaultdict(deque)
_revoked: set[str] = set()  # signed-out tokens, kept until the process restarts


def hash_password(password: str, salt_hex: str) -> str:
    return hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), bytes.fromhex(salt_hex), PBKDF2_ROUNDS).hex()


def _public(key: str) -> dict[str, Any]:
    name = _USERS[key][0]
    return {"username": key, "name": name, "initial": name[0].upper()}


def verify(username: str, password: str) -> dict[str, Any] | None:
    """Case-insensitive username, case-sensitive password. Returns the public user record."""
    key = (username or "").strip().lower()
    rec = _USERS.get(key)
    if rec is None:
        hash_password(password or "", "00" * 16)  # same cost whether or not the user exists
        return None
    if not hmac.compare_digest(hash_password(password or "", rec[1]), rec[2]):
        return None
    return _public(key)


# ---- rate limit ------------------------------------------------------------------------
def too_many_failures(addr: str, now: float | None = None) -> bool:
    now = time.time() if now is None else now
    q = _failures[addr]
    while q and now - q[0] > FAILURE_WINDOW_S:
        q.popleft()
    return len(q) >= MAX_FAILURES


def record_failure(addr: str, now: float | None = None) -> None:
    _failures[addr].append(time.time() if now is None else now)


def reset_rate_limit() -> None:
    _failures.clear()


# ---- tokens ----------------------------------------------------------------------------
def _sign(payload: str) -> str:
    return hmac.new(_SECRET, payload.encode("utf-8"), hashlib.sha256).hexdigest()


def issue_token(username: str, ttl_s: int = TOKEN_TTL_S) -> str:
    exp = int(time.time()) + int(ttl_s)
    payload = f"{username}.{exp}.{secrets.token_hex(8)}"  # nonce: two sign-ins never share a token
    raw = f"{payload}.{_sign(payload)}"
    return base64.urlsafe_b64encode(raw.encode("utf-8")).decode("ascii").rstrip("=")


def user_for_token(token: str | None) -> dict[str, Any] | None:
    if not token:
        return None
    try:
        raw = base64.urlsafe_b64decode(token + "=" * (-len(token) % 4)).decode("utf-8")
        username, exp_s, nonce, sig = raw.rsplit(".", 3)
        exp = int(exp_s)
    except (ValueError, UnicodeDecodeError):
        return None
    if not hmac.compare_digest(sig, _sign(f"{username}.{exp}.{nonce}")):
        return None
    if exp < time.time() or username not in _USERS or token in _revoked:
        return None
    return _public(username)


def revoke(token: str | None) -> None:
    """Sign-out: the token is refused from now on (in memory; it also expires on its own)."""
    if token:
        _revoked.add(token)
