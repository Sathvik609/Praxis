"""Write benchmark/results/cool_vs_stock_c8g.md from the raw per-round JSON of cool_bench.py.

Each round's file holds per-stage p50 / p95 for one build (`--label cool` or `stock`); the
table reports the median over rounds of each. The cost line divides the instance's hourly
price by its frames per hour at the measured p50, one stream at a time (OpenCV already uses
both vCPUs): a conservative compute-bound estimate, not a load test. The reading below the tables is kept by hand in
`cool_vs_stock_c8g.notes.md` and appended verbatim.

    python benchmark/summarize.py [--raw benchmark/results/raw] [--out benchmark/results/cool_vs_stock_c8g.md]
"""

from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent

STAGES = [
    ("decode", "JPEG decode (`imdecode`)"),
    ("aruco_H", "ArUco + homography + solvePnP (`Calibrator.run`)"),
    ("warp", "`warpPerspective` to canonical sheet"),
    ("hough", "Hole finding (`GaussianBlur` + `HoughCircles`)"),
    ("peg_mask", "Peg mask (`cvtColor` HSV + `inRange`)"),
    ("peg_blobs", "Peg blobs (mask + `findContours` + moments)"),
    ("hole_match", "Hole occupancy (masked `matchTemplate` x9)"),
    ("cup", "Cup (warp + `inRange` + `findContours`)"),
    ("pipeline_nhpt", "**Full NHPT frame** (`SessionPipeline.process`, classical)"),
    ("pipeline_cup", "**Full cup frame** (`SessionPipeline.process`, classical)"),
    ("hand_dnn", "Hand model (`cv2.dnn` palm + landmarks ONNX), not classical"),
]

# us-east-2 on-demand, 11 Oct 2026: c8g.large $0.0798/h; the COOL AMI adds $0.01/h (after its trial).
PRICE_PER_H = {"stock": 0.0798, "cool": 0.0798 + 0.01}


def load(raw: Path) -> dict[str, list[dict]]:
    runs: dict[str, list[dict]] = {}
    for f in sorted(raw.glob("*_r*.json")):
        d = json.loads(f.read_text())
        runs.setdefault(d["label"], []).append(d)
    return runs


def med(runs: list[dict], stage: str, key: str) -> float:
    return statistics.median(r["stages"][stage][key] for r in runs)


def cost_per_1000(ms: float, label: str) -> float:
    frames_per_h = 3_600_000 / ms  # one stream at a time; OpenCV already uses both vCPUs
    return PRICE_PER_H[label] / frames_per_h * 1000


def render(runs: dict[str, list[dict]], raw: Path) -> str:
    cool, stock = runs["cool"], runs["stock"]
    ec, es = cool[0]["env"], stock[0]["env"]
    def build_line(e: dict, prefix: str) -> str:
        return next((ln.split(":", 1)[1].strip() for ln in e.get("build", []) if ln.strip().startswith(prefix)), "")

    hal = lambda e: build_line(e, "Custom HAL")  # noqa: E731
    simd = lambda e: build_line(e, "Baseline")  # noqa: E731
    lines = [
        "# COOL vs stock OpenCV on Praxis's per-frame work",
        "",
        f"Generated by `benchmark/summarize.py` from {len(cool)} COOL and {len(stock)} stock rounds in `{raw.relative_to(HERE.parent)}/` "
        f"(`cool_bench.py`, {cool[0]['repeats']} passes per round, rounds alternating COOL / stock on the same instance). "
        "Numbers are the median over rounds of the per-call p50 / p95.",
        "",
        "Host: one **c8g.large** (AWS Graviton4, Neoverse-V2, 2 vCPU, 4 GiB), us-east-2, launched from the COOL Marketplace AMI "
        "`ami-005a9f90c70ba8d9b` (Cloud Optimized OpenCV for AWS Graviton). Same Praxis code, same input bytes, "
        f"{ec.get('threads')} OpenCV threads, Python {ec.get('python')}.",
        "",
        "| Build | `cv2.__version__` | Source | SIMD baseline | HAL |",
        "|---|---|---|---|---|",
        f"| COOL | {ec['cv2_version']} | `{Path(ec['cv2_file']).parent.parent}` | {simd(ec)} | {hal(ec)} |",
        f"| Stock | {es['cv2_version']} | pinned wheel `opencv-python-headless==5.0.0.93` | {simd(es)} | {hal(es)} |",
        "",
        "Inputs: the two replay clips in `evaluation/dataset_v0` (NHPT 185 frames, cup 517 frames), resized to 640x480 and "
        "JPEG-encoded at quality 80 once, so both builds time identical bytes.",
        "",
        f"| Stage (ms per frame, p50 / p95) | Stock {es['cv2_version']} | COOL {ec['cv2_version']} | Speed-up (stock/COOL p50) |",
        "|---|---|---|---|",
    ]
    for key, name in STAGES:
        if key not in cool[0]["stages"] or key not in stock[0]["stages"]:
            continue
        s50, s95, c50, c95 = med(stock, key, "p50_ms"), med(stock, key, "p95_ms"), med(cool, key, "p50_ms"), med(cool, key, "p95_ms")
        lines.append(f"| {name} | {s50:.3f} / {s95:.3f} | {c50:.3f} / {c95:.3f} | {s50 / c50:.2f}x |")
    lines += [
        "",
        "**Compute cost per 1,000 frames** (instance price per hour / frames per hour at the measured p50, one stream at a time "
        "with OpenCV on both vCPUs; a conservative estimate, not a load test; COOL adds $0.01/h for the AMI):",
        "",
        "| Workload | Stock ($0.0798/h) | COOL ($0.0898/h) |",
        "|---|---|---|",
    ]
    for key, name in (("pipeline_nhpt", "Full NHPT frame"), ("pipeline_cup", "Full cup frame"), ("hand_dnn", "Hand model")):
        s, c = med(stock, key, "p50_ms"), med(cool, key, "p50_ms")
        lines.append(f"| {name} | ${cost_per_1000(s, 'stock'):.6f} | ${cost_per_1000(c, 'cool'):.6f} |")
    notes = HERE / "results" / "cool_vs_stock_c8g.notes.md"
    if notes.exists():
        lines += ["", notes.read_text().rstrip()]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", type=Path, default=HERE / "results" / "raw_v1")
    ap.add_argument("--out", type=Path, default=HERE / "results" / "cool_vs_stock_c8g.md")
    a = ap.parse_args(argv)
    a.out.write_text(render(load(a.raw.resolve()), a.raw.resolve()))
    print(a.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
